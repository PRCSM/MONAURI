export const getProduct = (slug: string) => products.find((p) => p.slug === slug)
export const getProductById = (id: string) => products.find((p) => p.id === id)
export const getCategory = (slug: string) => categories.find((c) => c.slug === slug)
export const getCollection = (slug: string) => collections.find((c) => c.slug === slug)
export const bestsellers = () => products.filter((p) => p.bestseller).slice(0, 4)
export const productsByCollection = (slug: string) => products.filter((p) => p.collection === slug)
export const relatedProducts = (p: Product, n = 4) =>
  [
    ...products.filter((x) => x.id !== p.id && x.collection === p.collection),
    ...products.filter((x) => x.id !== p.id && x.collection !== p.collection && x.category === p.category),
  ].slice(0, n)
